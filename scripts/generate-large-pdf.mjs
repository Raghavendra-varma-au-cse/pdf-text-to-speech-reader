#!/usr/bin/env node
/**
 * Generate a deterministic large PDF for load/render/export testing.
 *
 * Usage:
 *   node scripts/generate-large-pdf.mjs [pages] [output]
 *
 * The default output is debug/fixtures/large-sample.pdf (git-ignored).
 * This script is intentionally dependency-free so it works in CI and on a
 * contributor's machine without installing a PDF library.
 */

import fs from 'node:fs';
import path from 'node:path';

const pages = Math.max(1, Math.min(2000, Number(process.argv[2] || 400)));
const output = path.resolve(
  process.argv[3] || path.join('debug', 'fixtures', 'large-sample.pdf')
);

const PAGE_W = 612;
const PAGE_H = 792;
const FONT_ID = 3 + pages * 2;

function escapePdfText(value) {
  return value.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function contentForPage(pageNumber) {
  const lines = [];
  lines.push('BT');
  lines.push('/F1 18 Tf');
  lines.push('72 720 Td');
  lines.push(`(ReadAloud large PDF fixture - page ${pageNumber} of ${pages}) Tj`);
  lines.push('/F1 11 Tf');
  lines.push('0 -34 Td');

  for (let line = 0; line < 34; line++) {
    const n = (pageNumber - 1) * 34 + line + 1;
    const text =
      `Sentence ${n}. The quick brown fox jumps over the lazy dog while the reader ` +
      `extracts text, highlights sentences, and speaks them aloud. ` +
      `Equation ${n}: x^2 + y^2 = z^2 and a - b = c.`;
    lines.push(`(${escapePdfText(text)}) Tj`);
    lines.push('0 -18 Td');
  }
  lines.push('ET');

  // A few separate text runs per page exercise multi-span sentence fragments.
  lines.push('BT');
  lines.push('/F1 10 Tf');
  lines.push('72 60 Td');
  lines.push(
    `(${escapePdfText(
      `Footer ${pageNumber}: generated by scripts/generate-large-pdf.mjs for performance testing.`
    )}) Tj`
  );
  lines.push('ET');

  return lines.join('\n');
}

const objects = new Map();

objects.set(1, '<< /Type /Catalog /Pages 2 0 R >>');

const kids = Array.from({ length: pages }, (_, index) => `${3 + index * 2} 0 R`).join(' ');
objects.set(2, `<< /Type /Pages /Kids [${kids}] /Count ${pages} >>`);
objects.set(FONT_ID, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');

for (let index = 0; index < pages; index++) {
  const pageId = 3 + index * 2;
  const contentId = pageId + 1;
  const stream = contentForPage(index + 1);
  objects.set(
    pageId,
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] ` +
      `/Resources << /Font << /F1 ${FONT_ID} 0 R >> >> /Contents ${contentId} 0 R >>`
  );
  objects.set(
    contentId,
    `<< /Length ${Buffer.byteLength(stream, 'ascii')} >>\nstream\n${stream}\nendstream`
  );
}

const maxObjectId = Math.max(...objects.keys());
let pdf = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n';
const offsets = new Array(maxObjectId + 1).fill(0);

for (let id = 1; id <= maxObjectId; id++) {
  offsets[id] = Buffer.byteLength(pdf, 'latin1');
  pdf += `${id} 0 obj\n${objects.get(id)}\nendobj\n`;
}

const xrefOffset = Buffer.byteLength(pdf, 'latin1');
pdf += `xref\n0 ${maxObjectId + 1}\n`;
pdf += '0000000000 65535 f \n';
for (let id = 1; id <= maxObjectId; id++) {
  pdf += `${String(offsets[id]).padStart(10, '0')} 00000 n \n`;
}
pdf += `trailer\n<< /Size ${maxObjectId + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, Buffer.from(pdf, 'latin1'));

console.log(
  `Generated ${pages} pages (${(Buffer.byteLength(pdf, 'latin1') / 1024).toFixed(0)} KB) -> ${output}`
);
